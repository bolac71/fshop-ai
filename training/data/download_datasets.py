"""
Download and unify public Vietnamese toxic/hate speech datasets.

Datasets:
  1. UIT-ViCTSD (tarudesu/ViCTSD on HuggingFace)
     https://huggingface.co/datasets/tarudesu/ViCTSD
     Columns: Comment, Toxicity (0/1), Constructiveness (0/1), Title, Topic
     → Auto-download via HuggingFace datasets library

  2. ViHSD (uitnlp/vihsd on HuggingFace)
     https://huggingface.co/datasets/uitnlp/vihsd
     label_id: 0=CLEAN, 1=OFFENSIVE, 2=HATE
     → Auto-download via HuggingFace datasets library

  3. Synthetic data
     → Generated by generate_synthetic.py

Target label schema (multi-label, each 0 or 1):
    toxic, spam, hate_speech

Output: training/data/unified_dataset.csv

Install: pip install datasets
"""

import csv
import json
import os
from pathlib import Path

from dotenv import load_dotenv

load_dotenv(Path(__file__).parents[2] / ".env")

DATA_DIR = Path(__file__).parent
HF_TOKEN = os.getenv("HF_TOKEN")  # optional — needed only for gated datasets


def load_victsd_hf() -> list[dict]:
    """Load UIT-ViCTSD from HuggingFace (tarudesu/ViCTSD)."""
    try:
        from datasets import load_dataset
    except ImportError:
        print("  [ERROR] Cần cài: pip install datasets")
        return []

    print("  Downloading tarudesu/ViCTSD from HuggingFace...", flush=True)
    try:
        ds = load_dataset("tarudesu/ViCTSD")
    except Exception as e:
        print(f"  [ERROR] {e}")
        return []

    rows = []
    for _, split_data in ds.items():
        for item in split_data:
            text = str(item.get("Comment", "")).strip()
            if not text:
                continue
            toxic = int(item.get("Toxicity", 0))
            rows.append({
                "text":        text,
                "toxic":       toxic,
                "spam":        0,
                "hate_speech": 0,
                "source":      "uit-victsd",
            })
    return rows


def load_vihs() -> list[dict]:
    """
    Load Vietnamese hate speech data.

    Primary: uitnlp/vihsd (gated — needs HF_TOKEN + access request at
             https://huggingface.co/datasets/uitnlp/vihsd)
    Fallback: tarudesu/ViHOS (public — Vietnamese Hate and Offensive Speech)

    label_id for vihsd: 0=CLEAN, 1=OFFENSIVE, 2=HATE
    label for ViHOS: 0=CLEAN, 1=HATE
    """
    try:
        from datasets import load_dataset
    except ImportError:
        print("  [ERROR] Cần cài: pip install datasets")
        return []

    # ── Primary: uitnlp/vihsd (gated) ─────────────────────────────────────
    if HF_TOKEN:
        print("  Trying uitnlp/vihsd (gated, using HF_TOKEN)...", flush=True)
        try:
            ds = load_dataset("uitnlp/vihsd", token=HF_TOKEN)
            rows = []
            for _, split_data in ds.items():
                for item in split_data:
                    text = str(item.get("free_text", item.get("comment", ""))).strip()
                    if not text:
                        continue
                    label_id = str(item.get("label_id", "0")).strip()
                    rows.append({
                        "text":        text,
                        "toxic":       1 if label_id in ("1", "2") else 0,
                        "spam":        0,
                        "hate_speech": 1 if label_id == "2" else 0,
                        "source":      "vihsd",
                    })
            print(f"  uitnlp/vihsd: {len(rows)} rows OK")
            return rows
        except Exception as e:
            print(f"  uitnlp/vihsd failed: {e}")
            print("  → Falling back to tarudesu/ViHOS...")
    else:
        print("  HF_TOKEN not set — uitnlp/vihsd is gated, skipping.")
        print("  → Using tarudesu/ViHOS (public fallback)...", flush=True)

    # ── Fallback: tarudesu/ViHOS (public) ─────────────────────────────────
    # Columns: text, label (0=CLEAN, 1=HATE)
    try:
        ds = load_dataset("tarudesu/ViHOS")
        rows = []
        for _, split_data in ds.items():
            for item in split_data:
                text = str(item.get("text", item.get("sentence", ""))).strip()
                if not text:
                    continue
                label = int(item.get("label", 0))
                rows.append({
                    "text":        text,
                    "toxic":       label,
                    "spam":        0,
                    "hate_speech": label,
                    "source":      "vihos",
                })
        print(f"  tarudesu/ViHOS: {len(rows)} rows OK")
        return rows
    except Exception as e:
        print(f"  [ERROR] tarudesu/ViHOS also failed: {e}")
        return []


def load_synthetic(json_path: Path) -> list[dict]:
    with open(json_path, encoding="utf-8") as f:
        return json.load(f)


def save_unified(rows: list[dict], output_path: Path):
    fieldnames = ["text", "toxic", "spam", "hate_speech", "source"]
    with open(output_path, "w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames, extrasaction="ignore")
        writer.writeheader()
        writer.writerows(rows)
    print(f"\nSaved {len(rows)} rows → {output_path}")


def main():
    all_rows: list[dict] = []

    # 1. UIT-ViCTSD from HuggingFace
    print("=== UIT-ViCTSD (HuggingFace: tarudesu/ViCTSD) ===")
    victsd_rows = load_victsd_hf()
    all_rows.extend(victsd_rows)
    print(f"UIT-ViCTSD: {len(victsd_rows)} rows loaded")

    # 2. ViHSD / ViHOS from HuggingFace
    print("\n=== ViHSD / ViHOS (HuggingFace) ===")
    vihs_rows = load_vihs()
    all_rows.extend(vihs_rows)
    print(f"ViHSD/ViHOS: {len(vihs_rows)} rows loaded")

    # 3. Synthetic data
    print("\n=== Synthetic ===")
    synthetic_path = DATA_DIR / "synthetic.json"
    if synthetic_path.exists():
        synth_rows = load_synthetic(synthetic_path)
        all_rows.extend(synth_rows)
        print(f"Synthetic: {len(synth_rows)} rows loaded")
    else:
        print("[SKIP] synthetic.json chưa có → chạy generate_synthetic.py trước")

    if not all_rows:
        print("\nKhông có data nào.")
        return

    save_unified(all_rows, DATA_DIR / "unified_dataset.csv")

    # Print label distribution
    total = len(all_rows)
    print("\nLabel distribution:")
    for label in ("toxic", "spam", "hate_speech"):
        count = sum(r[label] for r in all_rows)
        print(f"  {label:12s}: {count:5d} / {total} ({count/total*100:.1f}%)")

    # Source breakdown
    from collections import Counter
    sources = Counter(r["source"] for r in all_rows)
    print("\nSource breakdown:")
    for src, cnt in sources.most_common():
        print(f"  {src:15s}: {cnt}")


if __name__ == "__main__":
    main()
